-- ------------------------------------------------------------
-- 1) 並び順：北迫→西川→野口→秋山→藤井→小田→川村→振原→山本
--    ここに載っていない部員は、そのあとに続きます。
-- ------------------------------------------------------------
update public.members m
set sort_order = v.ord
from (values
  ('北迫', 1),
  ('西川', 2),
  ('野口', 3),
  ('秋山', 4),
  ('藤井', 5),
  ('小田', 6),
  ('川村', 7),
  ('振原', 8),
  ('山本', 9)
) as v(name, ord)
where m.name = v.name;

-- 指定外の部員は 100 番以降へ（名前順）
with rest as (
  select id, row_number() over (order by name) as rn
  from public.members
  where name not in ('北迫','西川','野口','秋山','藤井','小田','川村','振原','山本')
)
update public.members m
set sort_order = 100 + rest.rn
from rest
where m.id = rest.id;

-- ------------------------------------------------------------
-- 2) 「その他」の担当者名を入れる列を追加
--    部員マスタに無い人（助っ人・OBなど）を記録するために使う。
--    member_id が NULL で custom_member に名前が入っている状態になります。
-- ------------------------------------------------------------
alter table public.assignments
  add column if not exists custom_member text;
