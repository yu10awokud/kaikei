// ============================================================
// 金額の表示
//   金額は必ず整数（円）で扱う。小数は一切使わない。
// ============================================================

/** 1234567 → '¥1,234,567' */
export function formatYen(amount: number): string {
  return `¥${Math.trunc(amount).toLocaleString('ja-JP')}`;
}
